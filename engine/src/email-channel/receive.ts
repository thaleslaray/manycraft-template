import PostalMime from 'postal-mime'
import { stableId } from '../flow/types'
import { sourceOf, inboundEventSchema } from '../channels/core/queue'
import { ensureConversation, recordMessage } from '../inbox/service'
import { normalizeEmail, type EmailEnv } from './store'
import { emailEvent, sendEmailPart, mirrorOutbound, type StoredEmail } from './service'
import { stateInSql } from '../channels/core/connection-state'
export type ReplyInput = {
  from: string
  to: string
  messageId: string
  inReplyTo?: string
  /** Message-IDs of the References header, oldest first. */
  references?: string[]
  text: string
  /** The Date header of the message (ms). Mail arrives out of order: the conversation follows when it was written, not when it got here. */
  date?: number
}
/** Only a reply to an existing outbound recipient is accepted. No contact is created for unsolicited mail. */
export async function receiveReply(
  env: EmailEnv,
  input: ReplyInput,
): Promise<{
  accepted: boolean
  duplicate?: boolean
  conversationId?: string
}> {
  const token = input.to.match(/^reply\+([a-f0-9-]+)@/i)?.[1]
  const from = normalizeEmail(input.from)
  // Candidate ids: In-Reply-To and References. The id Cloudflare returns from send() is documented only as a
  // "Unique email ID" and the Message-ID header is generated by Cloudflare (headers.md, workers-api.md), so
  // none of these is guaranteed to match: the fallbacks below do not depend on them.
  const ids = [...new Set([input.inReplyTo, ...(input.references ?? [])].filter((id): id is string => !!id && id.length <= 512))].slice(0, 20)
  const base = `SELECT m.* FROM email_messages m JOIN channels ch ON ch.id=m.connection_id AND ch.workspace_id=m.workspace_id JOIN contacts c ON c.id=m.contact_id AND c.workspace_id=m.workspace_id WHERE m.status='sent' AND ${stateInSql(['connected'], 'ch')} AND c.status<>'deleted' AND m.recipient=?`
  const marks = ids.map(() => '?').join(',')
  let mail = (ids.length || token)
    ? await env.DB.prepare(`${base} AND (${[ids.length ? `m.message_id IN (${marks}) OR m.provider_message_id IN (${marks})` : '', token ? 'm.token=?' : ''].filter(Boolean).join(' OR ')}) ORDER BY m.created_at DESC LIMIT 1`)
        .bind(from, ...(ids.length ? [...ids, ...ids] : []), ...(token ? [token] : [])).first<StoredEmail>()
    : null
  // Senders on the customer's own domain have no reply+token address (the token only exists for platform senders)
  // and the client's In-Reply-To carries a Message-ID we never see. A person who was sent a message and answers
  // to the exact reply address stored for it is still a reply to the newest such message.
  if (!mail && input.to) {
    mail = await env.DB.prepare(`${base} AND lower(m.reply_to)=? ORDER BY m.created_at DESC LIMIT 1`).bind(from, normalizeEmail(input.to)).first<StoredEmail>()
  }
  if (!mail) return { accepted: false }
  if (!input.messageId.trim() || input.messageId.length > 512) return { accepted: false }
  const receipt = await env.DB.prepare(
    'INSERT INTO email_receipts(workspace_id,message_id,received_at) VALUES (?,?,?) ON CONFLICT(workspace_id,message_id) DO NOTHING',
  )
    .bind(mail.workspace_id, input.messageId, Date.now())
    .run()
  const duplicate = !receipt.meta.changes
  const storedReceipt = (await env.DB.prepare(
    'SELECT queued_at,received_at FROM email_receipts WHERE workspace_id=? AND message_id=?',
  )
    .bind(mail.workspace_id, input.messageId)
    .first<{ queued_at: number | null; received_at: number }>())!
  // A Date in the future or unreadable never moves the conversation: the time it reached us caps it.
  const at = input.date !== undefined && Number.isFinite(input.date) ? Math.min(input.date, storedReceipt.received_at) : storedReceipt.received_at
  const conversationId = await ensureConversation(env, mail.workspace_id, mail.contact_id, mail.connection_id)
  await recordMessage(env, {
    createdAt: at,
    id: `in-${await stableId(JSON.stringify([sourceOf('email'), mail.connection_id, input.messageId]))}`,
    workspaceId: mail.workspace_id,
    conversationId,
    direction: 'in',
    sender: 'contact',
    text: input.text,
    externalMessageId: `email:${mail.connection_id}:${normalizeEmail(input.from)}:${input.messageId}`,
    connectionId: mail.connection_id,
  })
  await env.DB.batch([
    env.DB.prepare(
      'UPDATE contacts SET last_input_text=CASE WHEN coalesce(last_interaction_at,0)<=? THEN ? ELSE last_input_text END,last_interaction_at=max(coalesce(last_interaction_at,0),?) WHERE workspace_id=? AND id=?',
    ).bind(
      at,
      input.text,
      at,
      mail.workspace_id,
      mail.contact_id,
    ),
    env.DB.prepare(
      'UPDATE contact_channels SET last_inbound_at=max(coalesce(last_inbound_at,0),?),window_expires_at=NULL,human_window_expires_at=NULL WHERE workspace_id=? AND contact_id=? AND channel_id=?',
    ).bind(at, mail.workspace_id, mail.contact_id, mail.connection_id),
  ])
  if (!duplicate && /^(stop|unsubscribe|parar|sair)$/i.test(input.text.trim())) {
    await emailEvent(env, mail, 'unsubscribed')
    const { stopSettings } = await import('./management')
    const { rt, config } = await stopSettings(env, mail.workspace_id, mail.connection_id)
    if (config?.enabled) {
      // Only this explicit confirmation is transactional. The optional automation retains marketing consent guards.
      if (config.text) {
        const result = await sendEmailPart(env, rt.connection, { kind: 'direct', externalUserId: mail.recipient }, { kind: 'text', text: config.text, email: { subject: config.subject } }, 'human')
        if (result.ok) {
          const confirmation = await env.DB.prepare('SELECT * FROM email_messages WHERE workspace_id=? AND message_id=? OR workspace_id=? AND provider_message_id=?').bind(mail.workspace_id, result.externalId, mail.workspace_id, result.externalId).first<StoredEmail>()
          if (confirmation) await mirrorOutbound(env, confirmation)
        }
      }
      if (config.automationId) {
        const { startEmailAutomation } = await import('./events')
        await startEmailAutomation(env, mail.workspace_id, mail.contact_id, mail.connection_id, config.automationId, `email-stop:${mail.workspace_id}:${input.messageId}`)
      }
    }
  }
  if (env.INBOUND) {
    // Two deliveries of the same Message-ID can run at once: only the one that wins this update queues the event.
    const claimed = await env.DB.prepare('UPDATE email_receipts SET queued_at=? WHERE workspace_id=? AND message_id=? AND queued_at IS NULL')
      .bind(Date.now(), mail.workspace_id, input.messageId).run()
    if (claimed.meta.changes) {
      try {
      await env.INBOUND.send(
        inboundEventSchema.parse({
          version: 1,
          provider: sourceOf('email'),
          workspaceId: mail.workspace_id,
          channelId: mail.connection_id,
          eventId: input.messageId,
          receivedAt: storedReceipt.received_at,
          payload: {
            type: 'reply',
            messageId: input.messageId,
            eventId: input.messageId,
            from: normalizeEmail(input.from),
            text: input.text,
            inReplyTo: mail.provider_message_id ?? mail.message_id,
            verifiedReply: true,
          },
        }),
      )
      } catch (error) {
        // The queue did not take it: release the claim so the next delivery of this message queues it.
        await env.DB.prepare('UPDATE email_receipts SET queued_at=NULL WHERE workspace_id=? AND message_id=?').bind(mail.workspace_id, input.messageId).run()
        throw error
      }
    }
  }
  return {
    accepted: true,
    conversationId,
    ...(duplicate ? { duplicate: true } : {}),
  }
}
/** Cloudflare Email Routing consumes MIME only once; parsing honors charset, transfer encoding and multipart. */
export async function receiveEmail(
  message: Pick<ForwardableEmailMessage, 'from' | 'to' | 'raw' | 'rawSize' | 'setReject'>,
  env: EmailEnv,
) {
  if (message.rawSize > 25 * 1024 * 1024) {
    message.setReject('Mensagem excede o limite de recebimento.')
    return
  }
  const parsed = await PostalMime.parse(await new Response(message.raw).arrayBuffer(), {
    maxNestingDepth: 20,
    maxHeadersSize: 64 * 1024,
  })
  const result = await receiveReply(env, {
    from: message.from,
    to: message.to,
    messageId: parsed.messageId ?? '',
    inReplyTo: parsed.inReplyTo,
    ...(parsed.references ? { references: parsed.references.match(/<[^<>\s]+>/g) ?? [] } : {}),
    ...(parsed.date && Number.isFinite(Date.parse(parsed.date)) ? { date: Date.parse(parsed.date) } : {}),
    text: (parsed.text ?? parsed.html?.replace(/<[^>]*>/g, ' ') ?? '').slice(0, 100000),
  })
  if (!result.accepted)
    message.setReject('Somente respostas a mensagens enviadas pela plataforma são aceitas.')
}
